package com.example.finsight.ai

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL
import java.net.UnknownHostException

const val GEMINI_MODEL = "gemini-4-hydrogen"

/**
 * Client for communicating with the Gemini REST API using HttpURLConnection.
 */
class GeminiClient {

    suspend fun generate(
        systemInstruction: String,
        history: List<ChatMessage>,
        userMessage: String
    ): Result<String> = withContext(Dispatchers.IO) {
        val apiKey = com.example.finsight.BuildConfig.GEMINI_API_KEY
        if (apiKey.isBlank()) {
            return@withContext Result.failure(
                Exception("Gemini API key is missing. Please set GEMINI_API_KEY in local.properties.")
            )
        }

        try {
            val url = URL("https://generativelanguage.googleapis.com/v1beta/models/$GEMINI_MODEL:generateContent")
            val connection = (url.openConnection() as HttpURLConnection).apply {
                requestMethod = "POST"
                connectTimeout = 30000
                readTimeout = 30000
                doOutput = true
                setRequestProperty("Content-Type", "application/json; charset=utf-8")
                setRequestProperty("x-goog-api-key", apiKey)
            }

            val requestJson = JSONObject().apply {
                if (systemInstruction.isNotBlank()) {
                    val sysInstObj = JSONObject().apply {
                        put("parts", JSONArray().put(JSONObject().put("text", systemInstruction)))
                    }
                    put("system_instruction", sysInstObj)
                }

                val contentsArr = JSONArray()
                for (msg in history) {
                    val role = if (msg.isUser) "user" else "model"
                    val contentObj = JSONObject().apply {
                        put("role", role)
                        put("parts", JSONArray().put(JSONObject().put("text", msg.text)))
                    }
                    contentsArr.put(contentObj)
                }

                val userMsgObj = JSONObject().apply {
                    put("role", "user")
                    put("parts", JSONArray().put(JSONObject().put("text", userMessage)))
                }
                contentsArr.put(userMsgObj)

                put("contents", contentsArr)
            }

            connection.outputStream.use { os ->
                os.write(requestJson.toString().toByteArray(Charsets.UTF_8))
            }

            val responseCode = connection.responseCode
            if (responseCode == 200) {
                val responseText = connection.inputStream.bufferedReader().use { it.readText() }
                val responseJson = JSONObject(responseText)
                val candidates = responseJson.optJSONArray("candidates")
                if (candidates != null && candidates.length() > 0) {
                    val text = candidates.getJSONObject(0)
                        .getJSONObject("content")
                        .getJSONArray("parts")
                        .getJSONObject(0)
                        .getString("text")
                    Result.success(text)
                } else {
                    Result.failure(Exception("No response content generated by model."))
                }
            } else {
                val errorMsg = when (responseCode) {
                    400, 401, 403 -> "Authentication error (HTTP $responseCode). Please verify your Gemini API key in local.properties."
                    404 -> "Model not found ($GEMINI_MODEL). Please check the GEMINI_MODEL setting."
                    429 -> "Rate limit exceeded (HTTP 429). Please try again in a minute."
                    else -> "API request failed with HTTP $responseCode."
                }
                Result.failure(Exception(errorMsg))
            }
        } catch (e: UnknownHostException) {
            Result.failure(Exception("Network error. Please check your internet connection."))
        } catch (e: IOException) {
            Result.failure(Exception("Network error. Please check your internet connection."))
        } catch (e: Exception) {
            Result.failure(Exception("An error occurred: ${e.message}"))
        }
    }
}
